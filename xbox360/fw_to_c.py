"""fw_to_c.py - erzeugt aus der Firmware-BinDatei den XAFWSLOT als C-Const-Objekt.

Der fertige Code liest die Firmware DANACH DIREKT AUS DEM GEMAPPTEN EIGENEN IMAGE:
kein NtCreateFile, kein FATX-Dirent-Risiko, keine Kill-Window, sofort ab t=0.

Der Slot hat IMMER die volle Kapazitaet (fw_slot.h, 0x20000) und den XAFWSLOT-
Marker:
  - mit FW-Datei: Daten ab Compile drin (Build-Pfad, z.B. CI oder Entwickler);
  - ohne FW-Datei: len=0, Daten null - das XEX wird so ausgeliefert und hinterher
    OHNE Toolchain mit tools/patch_slot.py befuellt (get-firmware [E]); der
    Patch schreibt in bereits gemappten Speicherbereich, also gleiche Sicherheit
    wie Compile-in, null Datei-I/O beim Boot.

Aufruf (aus build.sh):
  python3 fw_to_c.py OUT.c
Umgebungsvariable XA_FW: expliziter Pfad zur FW; leer gesetzt = Slot bewusst leer
(fuer Distributions-Builds, damit keine FW-Bytes ins Repo/XEX); gesetzt/gesetzt-
Default-Nichtexistenz = Defaultpfad firmware_cache/one_dongle_02fe.bin.
"""
import hashlib
import os
import sys

DEFAULT_FW = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..", "..", "firmware_cache", "one_dongle_02fe.bin"))

CAP = 0x20000  # XA_FW_SLOT_MAX in fw_slot.h

HEADER = """/* AUTOGENERATED by fw_to_c.py - NICHT handbearbeiten.
 * XAFWSLOT: firmware as a const slot inside the plugin image (fw_slot.h).
 * Read from mapped memory at t=0: zero file I/O, no FATX dirent kill-window.
 * Empty slot (len 0) -> tools/patch_slot.py fills it after download (get-firmware
 * [E]); either way the bytes end up in the mapped image, never behind a file open. */
#include \"fw_slot.h\"
"""


def emit(out_path, fw_path):
    data = b""
    if fw_path:
        if not os.path.isfile(fw_path):
            print(f"fw_to_c: FW-Datei fehlt ({fw_path}) - leerer Slot (len=0), "
                  f"patch_slot.py kann ihn spaeter befuellen")
        else:
            data = open(fw_path, "rb").read()
            if not (1024 <= len(data) <= CAP):
                sys.exit(f"FW-Laenge unerwartet: {len(data)}")
    note = (f"{len(data)} bytes sha256={hashlib.sha256(data).hexdigest()[:16]}"
            if data else "leerer Slot (len=0) - fuer patch_slot.py vorbehalten")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(HEADER)
        fh.write(f"/* {note} */\n")
        fh.write("const struct xa_fw_slot xa_fw_slot = {\n")
        fh.write("    { 'X', 'A', 'F', 'W', 'S', 'L', 'O', 'T' },\n")
        fh.write(f"    {len(data)},\n")
        fh.write("    {")
        for i in range(0, len(data), 16):
            chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
            fh.write(f"\n        {chunk},")
        if not data:
            fh.write(" 0x00")
        fh.write("\n    }\n};\n")
    print(f"fw_to_c: {out_path} <- {note}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    if len(sys.argv) > 2:
        fw = sys.argv[2]              # explizit
    elif "XA_FW" in os.environ:
        fw = os.environ["XA_FW"]      # gesetzt (auch leer = Slot leer lassen)
    else:
        fw = DEFAULT_FW               # Default
    emit(sys.argv[1], fw)
